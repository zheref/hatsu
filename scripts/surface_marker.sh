# surface_marker.sh -- the ONE reader of a placed copy's generated marker, sourced (never run) by
# the three readers that decide whether a placed copy is Hatsu's own (zheref/hatsu#531, SEC-7):
# scripts/surface_bootstrap.sh, scripts/permissions_pack.sh and hooks/session-start.sh with its
# three mirrors.
#
# WHY IT EXISTS. Each reader used to ask "does this file contain the marker's text anywhere in
# its bytes?", spelled three ways. The marker's text is also the form every document, comment and
# changelog uses to DESCRIBE it, so a prose file that only quoted a concrete marker satisfied the
# question, and the answer authorises an unattended full-surface install into a consumer's
# workspace (Feitan, F5 on the pull request closing zheref/hatsu#530). This file asks nen's own
# question, does the file carry a marker AT THE POSITION THE GENERATOR WRITES ONE?, with two
# differences, both deliberate: a JSON file is read at its line 2 only, where nen parses the whole
# document and takes the marker key wherever it sits, so this reader is the stricter one there;
# and the retired Antigravity generator's marker, which nen's reader does not know, is read too,
# where that generator wrote it (below).
#
# FROZEN TO FIXES ONLY (HR-392, docs/ROSTER.md; BC-11 as HR-171 reads it). A shell predicate is
# BC-11 debt: this file takes fixes and nothing new until nen ships a verb that reads one file's
# generated marker (zheref/nen#658) and Hatsu repins to it, and then it retires, each reader
# calling the verb.
#
# THE POSITION, read off nen's own `readMarker` (zheref/nen src/surface/mirror.ts). Exactly one
# line of the file is ever looked at:
#   - a file whose line 1 is `---` (frontmatter): the first line after the closing `---`; with no
#     closing fence there is no frontmatter, and line 1 (`---`) is no marker;
#   - a file whose line 1 starts `#!` (a hook script): line 2;
#   - a file whose line 1 is `{` (a JSON mirror): line 2, its first key;
#   - anything else: line 1.
# A trailing carriage return is dropped from every line, as nen drops it.
#
# THE LINE, and nothing else on it. TEXT is
#   GENERATED by nen surface mirror (surface: NAME) -- do not edit; edit the source and regenerate
# or, on a copy placed before zheref/hatsu#530 and not yet refreshed, the same with
# `(surface: NAME, stamp: VERSION)`. NAME holds no `,` and no `)`, as nen's own pattern says.
#   - markdown or TOML line: `<!-- TEXT -->` or `# TEXT`;
#   - hook script line 2:    `# TEXT`;
#   - JSON line 2:           `"$generated": "TEXT"` (optional comma), or `"TEXT": {` (native
#                            Antigravity hooks, whose one hook-definition name carries it),
#                            leading blanks allowed.
# The retired Antigravity generator's marker, `GENERATED for surface: antigravity -- do not edit;
# edit the source and regenerate`, is read only where that generator wrote it: `<!-- L -->` as the
# markdown line, `# <!-- L -->` as a hook script's line 2, `"description": "<!-- L -->",` as a
# JSON file's line 2.
#
# NAME IS COMPARED, NEVER MATCHED. The reader prints `nen:NAME` (or `legacy:antigravity`) and the
# caller compares it with `=`, so a surface name never reaches a pattern (CWE-625) and
# `codex-experimental` is not `codex`.
#
# PORTABILITY. POSIX sh and POSIX awk only, no `local`, every name prefixed `surface_marker` or
# `_sm_`: hooks/session-start.sh sources it on an installed host where only nen, git and gh are
# guaranteed, and the two bash readers source it under `set -euo pipefail`. Every function returns
# 0 or 1 and never fails the caller's shell on its own.

# _sm_run MODE FILE [SURFACE] -- the one awk run every function below is. The answer is awk's exit
# status (and, for `read`, its one line of output), so no function here opens a subshell of the
# calling shell: under a traced caller (the Bashcov capture of the surface-bootstrap lane) a
# subshell's trace records interleave with the caller's, and the program text never reaches the
# trace either, because it arrives as a here-document on awk's standard input rather than as an
# argument. MODE and SURFACE travel in the environment (ENVIRON), never through `awk -v`, which
# would process backslash escapes in the name. A file that cannot be read answers false. The answer
# is returned rather than left as the last status, so `set -e` in a caller never sees the reader
# fail on its own.
_sm_run() {
  # Silent under a caller's `set -x`, restored on the way out: the reader runs once per placed
  # file, and its own lines are not the caller's to trace.
  case $- in *x*) set +x; _sm_trace=1 ;; *) _sm_trace= ;; esac
  _sm_answer=1
  if [ -f "${2:-}" ]; then
    # A bare `name=value` operand is an assignment to awk, never a file: anchor a relative path.
    case "$2" in /*|./*) _sm_file="$2" ;; *) _sm_file="./$2" ;; esac
    _SM_MODE="$1" _SM_WANT="${3:-}" awk -f /dev/stdin "$_sm_file" 2>/dev/null <<'SURFACE_MARKER_AWK' && _sm_answer=0
function nen_text(x,   mid, i) {
  if (length(x) < length(P) + length(S)) return ""
  if (substr(x, 1, length(P)) != P) return ""
  if (substr(x, length(x) - length(S) + 1) != S) return ""
  mid = substr(x, length(P) + 1, length(x) - length(P) - length(S))
  if (index(mid, ")") > 0) return ""
  i = index(mid, ",")
  if (i == 0) return "nen:" mid
  if (substr(mid, i, 9) != ", stamp: ") return ""
  return "nen:" substr(mid, 1, i - 1)
}
function comment(x) {
  if (length(x) >= 9 && substr(x, 1, 5) == "<!-- " && substr(x, length(x) - 3) == " -->") return substr(x, 6, length(x) - 9)
  return NONE
}
function json_value(x,   v) {
  sub(/^[ \t]*:[ \t]*/, "", x)
  if (substr(x, 1, 1) != "\"") return NONE
  x = substr(x, 2)
  if (index(x, "\"") == 0) return NONE
  v = substr(x, 1, index(x, "\"") - 1)
  x = substr(x, index(x, "\"") + 1)
  if (x !~ /^,?[ \t]*$/) return NONE
  return v
}
function classify(c, kind,   x, k) {
  if (kind == "md") {
    x = comment(c)
    if (x != NONE) { if (x == L) return "legacy:antigravity"; return nen_text(x) }
    if (substr(c, 1, 2) == "# ") return nen_text(substr(c, 3))
    return ""
  }
  if (kind == "script") {
    if (substr(c, 1, 2) != "# ") return ""
    x = substr(c, 3)
    if (comment(x) == L) return "legacy:antigravity"
    return nen_text(x)
  }
  sub(/^[ \t]+/, "", c)
  if (substr(c, 1, 12) == "\"$generated\"") return nen_text(json_value(substr(c, 13)))
  if (substr(c, 1, 13) == "\"description\"") { if (comment(json_value(substr(c, 14))) == L) return "legacy:antigravity"; return "" }
  if (substr(c, 1, 1) != "\"") return ""
  x = substr(c, 2)
  if (index(x, "\"") == 0) return ""
  k = substr(x, 1, index(x, "\"") - 1)
  x = substr(x, index(x, "\"") + 1)
  if (x !~ /^[ \t]*:[ \t]*[{][ \t]*$/) return ""
  return nen_text(k)
}
BEGIN {
  P = "GENERATED by nen surface mirror (surface: "
  S = ") -- do not edit; edit the source and regenerate"
  L = "GENERATED for surface: antigravity -- do not edit; edit the source and regenerate"
  NONE = "\001"
  state = 0; kind = "md"; found = 0
}
{ sub(/\r$/, "") }
state == 0 {
  if ($0 == "---") { state = 1; next }
  if (substr($0, 1, 2) == "#!") { state = 3; kind = "script"; next }
  t = $0; gsub(/[ \t]/, "", t)
  if (t == "{") { state = 3; kind = "json"; next }
  cand = $0; found = 1; exit
}
state == 1 { if ($0 == "---") state = 2; next }
{ cand = $0; found = 1; exit }
END {
  r = ""
  if (found) r = classify(cand, kind)
  mode = ENVIRON["_SM_MODE"]
  if (mode == "read") { if (r == "") exit 1; print r; exit 0 }
  if (mode == "names") exit (ENVIRON["_SM_WANT"] != "" && r == "nen:" ENVIRON["_SM_WANT"]) ? 0 : 1
  if (mode == "legacy") exit (r == "legacy:antigravity") ? 0 : 1
  if (mode == "any") exit (r != "") ? 0 : 1
  exit 2
}
SURFACE_MARKER_AWK
  fi
  [ -z "$_sm_trace" ] || set -x
  return "$_sm_answer"
}

# surface_marker_read FILE -- prints `nen:NAME` or `legacy:antigravity` for the marker FILE carries
# at its generated position; prints nothing and returns 1 when it carries none (or is no file).
surface_marker_read() {
  _sm_run read "${1:-}"
}

# surface_marker_names FILE SURFACE -- true only when FILE's generated marker names SURFACE, in
# either nen grammar. The retired Antigravity marker never answers here.
surface_marker_names() {
  [ -n "${2:-}" ] || return 1
  _sm_run names "${1:-}" "$2"
}

# surface_marker_any FILE -- true when FILE carries any generated marker, nen's for any surface or
# the retired Antigravity one: the generic "a destination this bootstrap placed" question.
surface_marker_any() {
  _sm_run any "${1:-}"
}

# surface_marker_legacy FILE -- true only for the retired Antigravity generator's marker.
surface_marker_legacy() {
  _sm_run legacy "${1:-}"
}
