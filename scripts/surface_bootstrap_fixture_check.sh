[ ! -e "$antigravity_fixture/.agents/agents/stale-hatsu-agent.md" ] || fail "Antigravity full refresh kept a stale Hatsu persona"
case "$stale_output" in *"installed $antigravity_installed_count; removed stale stale-hatsu-skill,agents/stale-hatsu-agent.md") ;; *) fail "Antigravity refresh did not report its stale removal separately: $stale_output" ;; esac

