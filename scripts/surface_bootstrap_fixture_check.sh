cmp -s "$antigravity_fixture/.agents/rules/hatsu.md" "$hatsu_root/surfaces/antigravity/rules/hatsu.md" || fail "Antigravity rules content does not match the generated mirror"
[ -f "$antigravity_fixture/.agents/hooks.json" ] || fail "Antigravity hooks were not installed"
cmp -s "$antigravity_fixture/.agents/hooks.json" "$hatsu_root/surfaces/antigravity/hooks.json" || fail "Antigravity hooks content does not match the generated mirror"
