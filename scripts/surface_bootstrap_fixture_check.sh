grep -q '"Stop"' "$antigravity_fixture/.agents/hooks.json" || fail "Antigravity stop bell hook missing"
[ -x "$antigravity_fixture/.agents/hooks/guard-base-branch.sh" ] || fail "Antigravity guard hook script missing"
[ -x "$antigravity_fixture/.agents/hooks/stop-bell.sh" ] || fail "Antigravity stop bell hook script missing"
[ -x "$antigravity_fixture/.agents/hooks/session-start.sh" ] || fail "Antigravity session-start hook script missing"
[ "$(find "$antigravity_fixture/.agents/agents" -maxdepth 1 -name '[!_]*.md' -type f | wc -l | tr -d ' ')" = "$(find "$hatsu_root/surfaces/antigravity/agents" -maxdepth 1 -name '[!_]*.md' -type f | wc -l | tr -d ' ')" ] || fail "Antigravity personas were not fully installed under .agents/agents"
assert_ignored "$antigravity_fixture" '.agents/rules/hatsu.md'
assert_ignored "$antigravity_fixture" '.agents/hooks.json'
assert_ignored "$antigravity_fixture" '.agents/hooks/guard-base-branch.sh'
assert_ignored "$antigravity_fixture" '.agents/hooks/stop-bell.sh'
assert_ignored "$antigravity_fixture" '.agents/hooks/session-start.sh'
assert_ignored "$antigravity_fixture" '.agents/agents/kurapika.md'
assert_empty_untracked "$antigravity_fixture"
"$bootstrap" --surface antigravity --target "$antigravity_fixture" --install-all

mkdir -p "$antigravity_fixture/.agents/skills/stale-hatsu-skill"
printf '%s\n' '<!-- GENERATED for surface: antigravity -- do not edit; edit the source and regenerate -->' > "$antigravity_fixture/.agents/skills/stale-hatsu-skill/SKILL.md"
printf '%s\n' '<!-- GENERATED for surface: antigravity -- do not edit; edit the source and regenerate -->' > "$antigravity_fixture/.agents/agents/stale-hatsu-agent.md"
antigravity_installed_count=$(( $(count_skills "$(skills_source_dir antigravity)") + 1 + 1 \
  + $(count_files "$hatsu_root/surfaces/antigravity/hooks" '*.sh') \
  + $(find "$hatsu_root/surfaces/antigravity/agents" -maxdepth 1 -name '[!_]*.md' -type f | wc -l | tr -d ' ') ))
