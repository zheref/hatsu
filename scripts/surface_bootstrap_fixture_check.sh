#!/usr/bin/env bash
# Verify the first-run bootstrap against empty Codex and Cursor repositories.

set -euo pipefail
LC_ALL=C

script_dir="$(CDPATH='' cd -- "$(dirname -- "$0")" >/dev/null 2>&1 && pwd -P)"
hatsu_root="$(CDPATH='' cd -- "$script_dir/.." >/dev/null 2>&1 && pwd -P)"
bootstrap="$hatsu_root/scripts/surface_bootstrap.sh"
fixture_root="$(mktemp -d "${TMPDIR:-/tmp}/hatsu-surface-bootstrap.XXXXXX")"
trap 'rm -rf "$fixture_root"' EXIT

# HERMETIC HOOKS. hooks/session-start.sh's step 0 binds the host nen (scripts/nen_global.sh):
# it may fetch from the network and write ~/.local/bin, ~/.cache/nen and the shell profiles. No
# case here may reach the real HOME or the network, so the opt-out is exported for the whole
# script AND every hook invocation runs under a throwaway HOME/XDG tree that is asserted empty
# at the end (scripts/nen_global_fixture_check.sh owns the step-0 cases).
export HATSU_NEN_GLOBAL=0
hook_home="$fixture_root/hook-home"
mkdir -p "$hook_home"
hook_env() {
  env -u PLUGIN_ROOT -u CLAUDE_PLUGIN_ROOT HOME="$hook_home" XDG_CACHE_HOME="$hook_home/.cache" \
    XDG_CONFIG_HOME="$hook_home/.config" HATSU_NEN_GLOBAL=0 "$@"
}

fail() {
  echo "surface-bootstrap-fixture: $*" >&2
  exit 1
}

# --- skills_source_dir SURFACE -----------------------------------------------
# Same probe as scripts/surface_bootstrap.sh's own skills_source_dir():
# codex and cursor mirror skills flat, directly under surfaces/<surface>/;
# antigravity's are moving to surfaces/antigravity/skills/<name>/. Kept in
# sync with that script's own comment rather than hardcoded to either layout.
skills_source_dir() {
  local surface="$1"
  if [ -d "$hatsu_root/surfaces/$surface/skills" ]; then
    printf '%s' "$hatsu_root/surfaces/$surface/skills"
  else
    printf '%s' "$hatsu_root/surfaces/$surface"
  fi
}

count_skills() {
  local directory="$1" entry count=0
  for entry in "$directory"/*; do
    [ -f "$entry/SKILL.md" ] && count=$((count + 1))
  done
  printf '%s\n' "$count"
}

# --- count_files DIRECTORY PATTERN ------------------------------------------
# The number of top-level files matching PATTERN under DIRECTORY, or 0 for a
# directory that does not exist yet (a generator deliverable still landing,
# e.g. surfaces/antigravity/hooks/*.sh). Used to compute an EXPECTED "installed
# N" total from what is actually on disk, rather than a number retyped by hand
# every time a skill or persona is added -- the numeric literals this file used
# to carry went stale exactly that way (zheref/hatsu#93, 2026-09-20).
count_files() {
  local directory="$1" pattern="$2" entry count=0
  [ -d "$directory" ] || { printf '0\n'; return; }
  for entry in "$directory"/$pattern; do
    [ -f "$entry" ] && count=$((count + 1))
  done
  printf '%s\n' "$count"
}

assert_ignored() {
  git -C "$1" check-ignore -q -- "$2" || fail "$2 is not ignored through info/exclude"
}

assert_empty_untracked() {
  [ -z "$(git -C "$1" ls-files --others --exclude-standard)" ] || fail "$1 has non-ignored bootstrap files"
}

# --- mark_adopted DIRECTORY SURFACE ------------------------------------------
# Stamps the SECOND half of the --install-all adoption gate: a Hatsu-placed
# marker already sitting under that surface's own directory
# (.agents/skills/ten for codex AND antigravity, which share that
# skills path; .cursor/skills/ten for cursor). Used by every fixture
# below that calls --install-all directly, without a prior --bootstrap of its
# own, so the behavior each one actually tests is what's exercised rather than
# the adoption gate short-circuiting it with an early, unrelated exit 0.
mark_adopted() {
  # A DEDICATED marker name -- never "ten" itself -- so calling this
  # never interferes with a fixture's own assertions about whether
  # ten specifically got installed or stayed absent.
  #
  # The marker must NAME the surface it is adopting: `(surface: <surface>,`,
  # the same stamp form `nen surface mirror generate` writes
  # (`GENERATED by nen surface mirror (surface: codex, stamp: 0.43.0)`).
  # Codex and Antigravity share `.agents/`, so a marker with no surface name
  # would (wrongly) authorize either one's unattended full-surface install
  # off the other's adoption.
  local directory="$1" surface="$2" marker_dir
  case "$surface" in
    cursor) marker_dir="$directory/.cursor/skills/hatsu-adoption-marker" ;;
    *) marker_dir="$directory/.agents/skills/hatsu-adoption-marker" ;;
  esac
  mkdir -p "$marker_dir"
  printf 'GENERATED by nen surface mirror (surface: %s, stamp: fixture)\n' "$surface" > "$marker_dir/SKILL.md"
}

assert_fails() {
  local message="$1"
  shift
  if "$@" >/dev/null 2>&1; then
    fail "$message"
  fi
}

new_fixture() {
  local directory="$1"
  git init -q "$directory"
  git -C "$directory" config user.email 'fixture@example.invalid'
  git -C "$directory" config user.name 'Hatsu fixture'
  # Every fixture below represents an ALREADY-ADOPTED Hatsu consumer, unless
  # it explicitly says otherwise (the non-consumer / adoption-gate cases add
  # their own directory without this, or remove it before testing) --
  # scripts/surface_bootstrap.sh's --install-all now refuses on a target
  # carrying neither nen/contract.json nor nen/workflow.json (zheref/hatsu#94).
  mkdir -p "$directory/nen"
  printf '{}\n' > "$directory/nen/contract.json"
  # TRACKED, not left untracked: several fixtures below assert the target has
  # NO non-ignored untracked files after a bootstrap run, and an adoption
  # marker this helper itself planted must never be mistaken for one.
  git -C "$directory" add nen/contract.json
}

codex_fixture="$fixture_root/codex"
new_fixture "$codex_fixture"
"$bootstrap" --surface codex --target "$codex_fixture" --bootstrap
[ -f "$codex_fixture/.agents/skills/ten/SKILL.md" ] || fail "Codex warm-up was not seeded"
[ ! -e "$codex_fixture/.agents/skills/breath" ] || fail "Codex bootstrap installed more than ten"
grep -qx 'name: ten' "$codex_fixture/.agents/skills/ten/SKILL.md" || fail "Codex seed is not discoverable as ten"
assert_ignored "$codex_fixture" '.agents/skills/ten/SKILL.md'
assert_empty_untracked "$codex_fixture"
"$bootstrap" --surface codex --target "$codex_fixture" --bootstrap
"$bootstrap" --surface codex --target "$codex_fixture" --install-all
[ "$(count_skills "$codex_fixture/.agents/skills")" = "$(count_skills "$(skills_source_dir codex)")" ] || fail "Codex full refresh does not match its mirror"
grep -q '^<!-- BEGIN hatsu personas (generated — nen surface mirror, surface: codex) -->$' "$codex_fixture/AGENTS.override.md" || fail "Codex personas were not installed"
assert_ignored "$codex_fixture" 'AGENTS.override.md'
[ -f "$codex_fixture/.codex/hooks.json" ] || fail "Codex hooks were not installed"
# The placed copy is the mirror with PLUGIN_ROOT dropped from its root (CWE-426): Codex sets
# PLUGIN_ROOT only for plugin hooks, so a project-local hook must never read one from the environment.
grep -q '${PLUGIN_ROOT:-${HATSU_PLUGIN_ROOT:-./.codex}}' "$hatsu_root/surfaces/codex/hooks.json" || fail "the Codex mirror no longer carries the plugin root this fixture expects"
sed 's#${PLUGIN_ROOT:-${HATSU_PLUGIN_ROOT:-./.codex}}#${HATSU_PLUGIN_ROOT:-./.codex}#g' "$hatsu_root/surfaces/codex/hooks.json" |
  cmp -s - "$codex_fixture/.codex/hooks.json" || fail "Codex hooks content is not the generated mirror with PLUGIN_ROOT dropped"
! grep -qF '${PLUGIN_ROOT' "$codex_fixture/.codex/hooks.json" || fail "the placed Codex hooks still read PLUGIN_ROOT"
grep -q 'GENERATED by nen surface mirror' "$codex_fixture/.codex/hooks.json" || fail "the placed Codex hooks lost the generated marker"
assert_ignored "$codex_fixture" '.codex/hooks.json'
[ "$(count_files "$codex_fixture/.codex/agents" '*.toml')" = "$(count_files "$hatsu_root/surfaces/codex/agents" '*.toml')" ] || fail "Codex personas were not fully installed under .codex/agents"
assert_ignored "$codex_fixture" '.codex/agents/kurapika.toml'
[ "$(count_files "$codex_fixture/.codex/hooks" '*.sh')" = "$(count_files "$hatsu_root/surfaces/codex/hooks" '*.sh')" ] || fail "Codex hook scripts were not fully installed under .codex/hooks"
if [ -f "$codex_fixture/.codex/hooks/session-start.sh" ]; then
  [ -x "$codex_fixture/.codex/hooks/session-start.sh" ] || fail "Codex hook script session-start.sh is not executable"
  cmp -s "$codex_fixture/.codex/hooks/session-start.sh" "$hatsu_root/surfaces/codex/hooks/session-start.sh" || fail "Codex hook script content does not match the generated mirror"
  assert_ignored "$codex_fixture" '.codex/hooks/session-start.sh'
fi
assert_empty_untracked "$codex_fixture"
"$bootstrap" --surface codex --target "$codex_fixture" --install-all

mkdir -p "$codex_fixture/.agents/skills/stale-hatsu-skill"
printf '%s\n' 'GENERATED by nen surface mirror' > "$codex_fixture/.agents/skills/stale-hatsu-skill/SKILL.md"
printf '%s\n' 'GENERATED by nen surface mirror' > "$codex_fixture/.codex/agents/stale-hatsu-agent.toml"
codex_installed_count=$(( $(count_skills "$(skills_source_dir codex)") + 1 + 1 + $(count_files "$hatsu_root/surfaces/codex/agents" '*.toml') + $(count_files "$hatsu_root/surfaces/codex/hooks" '*.sh') ))
stale_output="$("$bootstrap" --surface codex --target "$codex_fixture" --install-all)"
[ ! -e "$codex_fixture/.agents/skills/stale-hatsu-skill" ] || fail "Codex full refresh kept a stale Hatsu skill"
[ ! -e "$codex_fixture/.codex/agents/stale-hatsu-agent.toml" ] || fail "Codex full refresh kept a stale Hatsu persona"
case "$stale_output" in *"installed $codex_installed_count; removed stale stale-hatsu-skill,agents/stale-hatsu-agent.toml") ;; *) fail "Codex refresh did not report its stale removal separately: $stale_output" ;; esac

# --- --plugin (Codex only): Codex installs Hatsu as a first-party plugin ---
# (`codex plugin add hatsu@hatsu`, which already serves every canonical skill
# and .codex-plugin/plugin.json's own hooks.json -- WHY, this task's own
# dispatch). Personas are still ours to place (a Codex plugin carries no
# personas); skills and hooks are the plugin's, so --plugin places neither
# and REMOVES whichever of either kind this bootstrap placed before. State
# below is built BY HAND rather than through a real prior --install-all, so
# these cases stay hermetic regardless of whether every canonical skill's
# codex mirror happens to be complete at fixture-run time (it is not,
# mid-development, exactly the situation this hermetic construction exists
# to be immune to).

plugin_only_fixture="$fixture_root/plugin-only"
new_fixture "$plugin_only_fixture"
mark_adopted "$plugin_only_fixture" codex
plugin_only_output="$("$bootstrap" --surface codex --target "$plugin_only_fixture" --install-all --plugin)"
[ ! -e "$plugin_only_fixture/.agents/skills/ten" ] || fail "--plugin placed a skill (ten)"
[ -z "$(find "$plugin_only_fixture/.agents/skills" -mindepth 1 -print -quit 2>/dev/null)" ] || fail "--plugin left something under .agents/skills"
[ ! -e "$plugin_only_fixture/.codex/hooks.json" ] || fail "--plugin placed .codex/hooks.json"
[ ! -e "$plugin_only_fixture/.codex/hooks" ] || fail "--plugin placed .codex/hooks scripts"
grep -q '^<!-- BEGIN hatsu personas (generated — nen surface mirror, surface: codex) -->$' "$plugin_only_fixture/AGENTS.override.md" || fail "--plugin did not place AGENTS.override.md personas"
[ "$(count_files "$plugin_only_fixture/.codex/agents" '*.toml')" = "$(count_files "$hatsu_root/surfaces/codex/agents" '*.toml')" ] || fail "--plugin did not place every persona under .codex/agents"
assert_ignored "$plugin_only_fixture" 'AGENTS.override.md'
assert_ignored "$plugin_only_fixture" '.codex/agents/kurapika.toml'
assert_empty_untracked "$plugin_only_fixture"
case "$plugin_only_output" in
  *"removed (the Codex plugin serves it): hatsu-adoption-marker"*) ;;
  *) fail "--plugin did not remove the marker skill it found under .agents/skills: $plugin_only_output" ;;
esac
case "$plugin_only_output" in *"codex plugin mode: skills and hooks served by the plugin"*) ;; *) fail "--plugin did not report its mode: $plugin_only_output" ;; esac

# --plugin after a skill AND a hooks set this bootstrap placed before: both
# kinds are removed and reported apart from ordinary stale-skill replacement
# ("removed (the Codex plugin serves it)" rather than "removed stale"),
# because the reason is not that a skill was dropped from the canonical set,
# it is that the Codex plugin now serves the destination.
plugin_after_full_fixture="$fixture_root/plugin-after-full"
new_fixture "$plugin_after_full_fixture"
mkdir -p "$plugin_after_full_fixture/.agents/skills/ten" "$plugin_after_full_fixture/.codex/hooks" "$plugin_after_full_fixture/.codex/agents"
printf 'name: ten\nGENERATED by nen surface mirror (surface: codex, stamp: fixture)\n' > "$plugin_after_full_fixture/.agents/skills/ten/SKILL.md"
printf '%s\n' '{"GENERATED by nen surface mirror (surface: codex,": true}' > "$plugin_after_full_fixture/.codex/hooks.json"
printf '#!/bin/sh\n# GENERATED by nen surface mirror (surface: codex, stamp: fixture)\n' > "$plugin_after_full_fixture/.codex/hooks/session-start.sh"
chmod +x "$plugin_after_full_fixture/.codex/hooks/session-start.sh"
{
  printf '%s\n' '<!-- BEGIN hatsu personas (generated — nen surface mirror, surface: codex) -->'
  printf 'fake persona body\n'
  printf '%s\n' '<!-- END hatsu personas (generated — nen surface mirror, surface: codex) -->'
} > "$plugin_after_full_fixture/AGENTS.override.md"
plugin_after_full_output="$("$bootstrap" --surface codex --target "$plugin_after_full_fixture" --install-all --plugin)"
[ ! -e "$plugin_after_full_fixture/.agents/skills/ten" ] || fail "--plugin after a full install kept the ten skill"
[ ! -e "$plugin_after_full_fixture/.codex/hooks.json" ] || fail "--plugin after a full install kept hooks.json"
[ ! -e "$plugin_after_full_fixture/.codex/hooks/session-start.sh" ] || fail "--plugin after a full install kept a hook script"
case "$plugin_after_full_output" in
  *"removed (the Codex plugin serves it): ten,.codex/hooks.json,.codex/hooks/session-start.sh"*) ;;
  *) fail "--plugin did not report its removals under the plugin-mode phrase: $plugin_after_full_output" ;;
esac

# A foreign (unmarked, or TRACKED) .agents/skills/aka is kept, untouched, and
# NAMED -- --plugin's removal pass is exactly as conservative as every other
# ownership check this script already makes.
plugin_foreign_fixture="$fixture_root/plugin-foreign-skill"
new_fixture "$plugin_foreign_fixture"
mark_adopted "$plugin_foreign_fixture" codex
mkdir -p "$plugin_foreign_fixture/.agents/skills/aka"
printf 'third-party aka skill, not ours\n' > "$plugin_foreign_fixture/.agents/skills/aka/SKILL.md"
plugin_foreign_output="$("$bootstrap" --surface codex --target "$plugin_foreign_fixture" --install-all --plugin)"
grep -qx 'third-party aka skill, not ours' "$plugin_foreign_fixture/.agents/skills/aka/SKILL.md" || fail "--plugin touched a foreign (unmarked) skill"
case "$plugin_foreign_output" in *"kept existing aka"*) ;; *) fail "--plugin did not report the foreign skill as kept: $plugin_foreign_output" ;; esac

plugin_tracked_fixture="$fixture_root/plugin-tracked-skill"
new_fixture "$plugin_tracked_fixture"
mark_adopted "$plugin_tracked_fixture" codex
mkdir -p "$plugin_tracked_fixture/.agents/skills/aka"
printf 'tracked aka skill, not ours\n' > "$plugin_tracked_fixture/.agents/skills/aka/SKILL.md"
git -C "$plugin_tracked_fixture" add .agents/skills/aka/SKILL.md
plugin_tracked_output="$("$bootstrap" --surface codex --target "$plugin_tracked_fixture" --install-all --plugin)"
grep -qx 'tracked aka skill, not ours' "$plugin_tracked_fixture/.agents/skills/aka/SKILL.md" || fail "--plugin touched a tracked skill"
case "$plugin_tracked_output" in *"kept existing aka"*) ;; *) fail "--plugin did not report the tracked skill as kept: $plugin_tracked_output" ;; esac

# --plugin is refused outside codex+--install-all, at exit 2, before touching
# the target at all.
plugin_bad_combo_fixture="$fixture_root/plugin-bad-combo"
new_fixture "$plugin_bad_combo_fixture"
set +e
plugin_bootstrap_output="$("$bootstrap" --surface codex --target "$plugin_bad_combo_fixture" --bootstrap --plugin 2>&1)"
plugin_bootstrap_rc=$?
set -e
[ "$plugin_bootstrap_rc" -eq 2 ] || fail "--plugin with --bootstrap did not exit 2: $plugin_bootstrap_output"
case "$plugin_bootstrap_output" in *"--plugin is valid only with --surface codex --install-all"*) ;; *) fail "--plugin with --bootstrap gave an unexpected message: $plugin_bootstrap_output" ;; esac
[ ! -e "$plugin_bad_combo_fixture/.agents" ] || fail "--plugin with --bootstrap touched the target"

set +e
plugin_cursor_output="$("$bootstrap" --surface cursor --target "$plugin_bad_combo_fixture" --install-all --plugin 2>&1)"
plugin_cursor_rc=$?
set -e
[ "$plugin_cursor_rc" -eq 2 ] || fail "--plugin with --surface cursor did not exit 2: $plugin_cursor_output"
case "$plugin_cursor_output" in *"--plugin is valid only with --surface codex --install-all"*) ;; *) fail "--plugin with --surface cursor gave an unexpected message: $plugin_cursor_output" ;; esac
[ ! -e "$plugin_bad_combo_fixture/.cursor" ] || fail "--plugin with --surface cursor touched the target"

# Adoption via our OWN AGENTS.override.md alone (its BEGIN/END hatsu personas
# markers), with NO marker anywhere under .agents -- exactly the state a
# PRIOR --plugin run leaves behind once it has removed every skill that could
# have carried has_marker_under's own marker.
plugin_override_adoption_fixture="$fixture_root/plugin-override-adoption"
new_fixture "$plugin_override_adoption_fixture"
{
  printf '%s\n' '<!-- BEGIN hatsu personas (generated — nen surface mirror, surface: codex) -->'
  printf 'fake persona body\n'
  printf '%s\n' '<!-- END hatsu personas (generated — nen surface mirror, surface: codex) -->'
} > "$plugin_override_adoption_fixture/AGENTS.override.md"
[ ! -d "$plugin_override_adoption_fixture/.agents" ] || fail "test setup: .agents should not exist yet"
plugin_override_adoption_output="$("$bootstrap" --surface codex --target "$plugin_override_adoption_fixture" --install-all --plugin)"
case "$plugin_override_adoption_output" in
  *"carries no existing codex mirror marker"*) fail "adoption via AGENTS.override.md alone was refused: $plugin_override_adoption_output" ;;
  *) ;;
esac
[ "$(count_files "$plugin_override_adoption_fixture/.codex/agents" '*.toml')" = "$(count_files "$hatsu_root/surfaces/codex/agents" '*.toml')" ] || fail "adoption via AGENTS.override.md alone did not place every persona"
[ ! -e "$plugin_override_adoption_fixture/.agents/skills/ten" ] || fail "adoption via AGENTS.override.md alone placed a skill"

# --- CWE-59 (Feitan): --plugin mode's removal pass (remove_plugin_served_skills,
# remove_plugin_served_hooks) skipped ensure_local_directory's own tracked-parent
# and symlinked-parent refusal for .agents/skills and .codex/hooks, so a
# symlinked (tracked or untracked) parent could send the enumeration -- and
# transaction_remove's `mv` -- outside the target. Adoption here is via
# AGENTS.override.md alone (the same technique as plugin_override_adoption_fixture
# above), so has_marker_under's own read-only `find -L` traversal into the
# hostile symlink is the only thing that ever looks inside it; nothing under
# the outside directory is ever moved or removed once the fix is in place.
outside_tracked_symlink_skills="$fixture_root/outside-tracked-symlink-skills"
mkdir -p "$outside_tracked_symlink_skills"
printf 'do not delete me (tracked symlink repro)\n' > "$outside_tracked_symlink_skills/victim.txt"
plugin_tracked_symlink_skills_fixture="$fixture_root/plugin-tracked-symlink-skills"
new_fixture "$plugin_tracked_symlink_skills_fixture"
{
  printf '%s\n' '<!-- BEGIN hatsu personas (generated — nen surface mirror, surface: codex) -->'
  printf 'fake persona body\n'
  printf '%s\n' '<!-- END hatsu personas (generated — nen surface mirror, surface: codex) -->'
} > "$plugin_tracked_symlink_skills_fixture/AGENTS.override.md"
mkdir -p "$plugin_tracked_symlink_skills_fixture/.agents"
ln -s "../../outside-tracked-symlink-skills" "$plugin_tracked_symlink_skills_fixture/.agents/skills"
git -C "$plugin_tracked_symlink_skills_fixture" add .agents/skills
assert_fails "a TRACKED symlinked .agents/skills was accepted under --plugin (Feitan CWE-59)" \
  "$bootstrap" --surface codex --target "$plugin_tracked_symlink_skills_fixture" --install-all --plugin
[ -f "$outside_tracked_symlink_skills/victim.txt" ] || fail "a tracked symlinked .agents/skills let --plugin delete a file outside the target"
grep -qx 'do not delete me (tracked symlink repro)' "$outside_tracked_symlink_skills/victim.txt" || fail "a tracked symlinked .agents/skills let --plugin modify a file outside the target"

outside_untracked_symlink_skills="$fixture_root/outside-untracked-symlink-skills"
mkdir -p "$outside_untracked_symlink_skills"
printf 'do not delete me (untracked skills symlink repro)\n' > "$outside_untracked_symlink_skills/victim.txt"
plugin_untracked_symlink_skills_fixture="$fixture_root/plugin-untracked-symlink-skills"
new_fixture "$plugin_untracked_symlink_skills_fixture"
{
  printf '%s\n' '<!-- BEGIN hatsu personas (generated — nen surface mirror, surface: codex) -->'
  printf 'fake persona body\n'
  printf '%s\n' '<!-- END hatsu personas (generated — nen surface mirror, surface: codex) -->'
} > "$plugin_untracked_symlink_skills_fixture/AGENTS.override.md"
mkdir -p "$plugin_untracked_symlink_skills_fixture/.agents"
ln -s "$outside_untracked_symlink_skills" "$plugin_untracked_symlink_skills_fixture/.agents/skills"
assert_fails "an UNTRACKED symlinked .agents/skills was accepted under --plugin (Feitan CWE-59)" \
  "$bootstrap" --surface codex --target "$plugin_untracked_symlink_skills_fixture" --install-all --plugin
[ -f "$outside_untracked_symlink_skills/victim.txt" ] || fail "an untracked symlinked .agents/skills let --plugin delete a file outside the target"
grep -qx 'do not delete me (untracked skills symlink repro)' "$outside_untracked_symlink_skills/victim.txt" || fail "an untracked symlinked .agents/skills let --plugin modify a file outside the target"

outside_untracked_symlink_hooks="$fixture_root/outside-untracked-symlink-hooks"
mkdir -p "$outside_untracked_symlink_hooks"
printf 'do not delete me (untracked hooks symlink repro)\n' > "$outside_untracked_symlink_hooks/victim.txt"
plugin_untracked_symlink_hooks_fixture="$fixture_root/plugin-untracked-symlink-hooks"
new_fixture "$plugin_untracked_symlink_hooks_fixture"
mark_adopted "$plugin_untracked_symlink_hooks_fixture" codex
mkdir -p "$plugin_untracked_symlink_hooks_fixture/.codex"
ln -s "$outside_untracked_symlink_hooks" "$plugin_untracked_symlink_hooks_fixture/.codex/hooks"
assert_fails "an UNTRACKED symlinked .codex/hooks was accepted under --plugin (Feitan CWE-59)" \
  "$bootstrap" --surface codex --target "$plugin_untracked_symlink_hooks_fixture" --install-all --plugin
[ -f "$outside_untracked_symlink_hooks/victim.txt" ] || fail "an untracked symlinked .codex/hooks let --plugin delete a file outside the target"
grep -qx 'do not delete me (untracked hooks symlink repro)' "$outside_untracked_symlink_hooks/victim.txt" || fail "an untracked symlinked .codex/hooks let --plugin modify a file outside the target"

# --- Phinks (Feitan note): is_ours accepted ANY surface's marker, and Codex
# and Antigravity share .agents/skills, so `--surface codex --install-all
# --plugin` used to remove every Antigravity-stamped skill it found there
# too. Only Codex's OWN stamped placements are removed; an Antigravity
# placement sharing the directory survives, and is named kept.
plugin_antigravity_survives_fixture="$fixture_root/plugin-antigravity-survives"
new_fixture "$plugin_antigravity_survives_fixture"
mark_adopted "$plugin_antigravity_survives_fixture" codex
mkdir -p "$plugin_antigravity_survives_fixture/.agents/skills/antigravity-owned"
