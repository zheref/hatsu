mark_adopted "$deleted_cursor_fixture" cursor
mkdir -p "$deleted_cursor_fixture/.cursor/skills/aka" "$deleted_cursor_fixture/.cursor/agents"
printf 'tracked then deleted Cursor skill\n' > "$deleted_cursor_fixture/.cursor/skills/aka/SKILL.md"
